def check_response_time(start_time: float, end_time: float, max_seconds: float = 2.0) -> bool:
    """Check if response time is within allowed limit."""
    elapsed = end_time - start_time
    return elapsed <= max_seconds

def check_length(text: str, min_len: int = 10, max_len: int = 20000000000) -> bool:
    """Check if text length is within range."""
    return min_len <= len(text) <= max_len

def check_schema(data: dict) -> bool:
    """Validate against predefined schema."""
    try:
        #AIResponseSchema(**data)
        check_response_contains_keywords(data)  # Use the keyword check function for validation
        return True
    except ValidationError as e:
        print("Schema validation error:", e)
        return False

