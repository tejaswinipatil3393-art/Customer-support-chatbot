def detect_hallucination(llm_output: str, reference_text: str, threshold: float = 0.75) -> bool:
    """
    Detects possible hallucinations by comparing LLM output with trusted reference text.
    
    Args:
        llm_output (str): The text generated by the LLM.
        reference_text (str): The trusted source text.
        threshold (float): Similarity threshold (0-1). Lower means stricter detection.
    
    Returns:
        bool: True if hallucination is suspected, False otherwise.
    """
    if not llm_output.strip() or not reference_text.strip():
        raise ValueError("Both LLM output and reference text must be non-empty strings.")

    # Load a semantic similarity model
    model = SentenceTransformer('all-MiniLM-L6-v2')

    # Encode both texts
    embeddings = model.encode([llm_output, reference_text], convert_to_tensor=True)

    # Compute cosine similarity
    similarity_score = util.cos_sim(embeddings[0], embeddings[1]).item()

    print(f"Similarity Score: {similarity_score:.4f}")

    # If similarity is below threshold, flag as hallucination
    return similarity_score < threshold
