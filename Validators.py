def check_response_contains_keywords(response: str) -> bool:
    """Check if response contains all required keywords."""
    assert isinstance(response, dict), "Response should be a dictionary"
    assert "results" in response, "Response should contain 'results' key"
    assert isinstance(response["results"], list), "Results should be a list"
    assert response["results"], "At least one result should be returned"
    
    for result in response["results"]:
        assert "title" in result, "Each result should contain 'title' field"
        assert "url" in result, "Each result should contain 'url' field"
        assert "content" in result, "Each result should contain 'content' field"

    return True  # If all checks pass, return True

